"""Demo projects: the synthetic office (known answers) and the Edinburgh real file."""
from __future__ import annotations

import json
import shutil
import urllib.request
from pathlib import Path

from . import project, synthetic

SYNTH_ID = "demo-synthetic"
EDI_ID = "demo-edinburgh"
EDI_URL = "https://datashare.ed.ac.uk/server/api/core/bitstreams/5926ee32-810b-46ab-91c4-9c51f284834a/content"
EDI_CREDIT = ("Real-file demo data: Valero, Enrique (2021). Synthetic building [dataset]. Cyberbuild Lab, "
              "The University of Edinburgh. https://doi.org/10.7488/ds/2893 — licensed CC BY 4.0. "
              "File used unmodified.")
SYNTH_CREDIT = "Synthetic demo data generated by ScanGap (simulated TLS, 0.4° steps)."


def demo_dir() -> Path:
    d = project.data_root() / "demo-data"
    d.mkdir(parents=True, exist_ok=True)
    return d


def build_synthetic(regenerate: bool = False, step_deg: float = 0.4) -> dict:
    src = demo_dir() / "synthetic"
    synthetic.write_demo_inputs(src)
    cloud = src / "synthetic_office_L1.e57"
    if regenerate or not cloud.exists():
        cloud = synthetic.generate(src, step_deg=step_deg)
    p = project.create("Harbor Street Office — Level 1 (synthetic)", pid=SYNTH_ID)
    pid = p["id"]
    p["credit"] = SYNTH_CREDIT
    p["spec"].update(client="Northwind Properties LLC", site="Harbor Street, Level 1")
    p["zones"] = synthetic.zones_json()
    p["settings"]["default_min_density"] = synthetic.DEMO_MIN_DENSITY
    for kind, name in (("plan", "scan_plan.csv"), ("registration", "registration.csv")):
        p["inputs"][kind] = str(project.store_input(pid, kind, name, (src / name).read_bytes()))
    project.save(p)
    project.ingest_cloud(pid, str(cloud))

    scope_path = project.store_input(pid, "scope", "scope.txt", (src / "scope.txt").read_bytes())
    project.set_scope(pid, scope_path, mode="offline")
    # a reviewer accepted every requirement whose quote was verified
    p = project.load(pid)
    for r in p["requirements"]:
        r["status"] = "accepted" if r["quote_verified"] else "rejected"
    project.save(p)
    project.apply_requirements(pid)

    files = json.loads((src / "delivery_manifest.json").read_text())
    for f in files:
        if f["name"].endswith(".e57"):
            f["path"] = str(cloud)  # this one is inspected; the rest are listed only
    project.set_manifest_files(pid, files)
    return project.analyze(pid)


def fetch_edinburgh(dest: Path | None = None) -> Path:
    dest = dest or demo_dir() / "edinburgh" / "cloud_coloured.e57"
    if dest.exists() and dest.stat().st_size > 1_000_000:
        return dest
    dest.parent.mkdir(parents=True, exist_ok=True)
    tmp = dest.with_suffix(".part")
    with urllib.request.urlopen(EDI_URL, timeout=120) as r, open(tmp, "wb") as f:
        shutil.copyfileobj(r, f)
    with open(tmp, "rb") as f:
        if f.read(8) != b"ASTM-E57":
            tmp.unlink()
            raise RuntimeError("Download did not return an E57 file.")
    tmp.replace(dest)
    return dest


# Zones on the interior wall faces, measured from the cloud (walls are 0.30 m thick).
EDI_ZONES = [
    {"id": "E1", "name": "North space", "polygon": [[0.30, 4.60], [12.20, 4.60], [12.20, 7.70], [0.30, 7.70]], "floor": 0},
    {"id": "E2", "name": "South-west space", "polygon": [[0.30, 0.30], [4.30, 0.30], [4.30, 4.30], [0.30, 4.30]], "floor": 0},
    {"id": "E3", "name": "South-east space", "polygon": [[4.60, 0.30], [12.20, 0.30], [12.20, 4.30], [4.60, 4.30]], "floor": 0},
]


def build_edinburgh(path: str | None = None) -> dict:
    cloud = Path(path) if path else fetch_edinburgh()
    p = project.create("Edinburgh synthetic building (real E57)", pid=EDI_ID)
    pid = p["id"]
    p["credit"] = EDI_CREDIT
    p["spec"].update(site="Cyberbuild Lab dataset", intended_use=None, units="m")
    p["zones"] = [dict(z, loa=None, min_density=None, in_scope=True) for z in EDI_ZONES]
    project.save(p)
    project.ingest_cloud(pid, str(cloud))
    return project.analyze(pid)
